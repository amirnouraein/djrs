"""JSON (from `djrs extract`) to a Cargo crate built on djrs-runtime.

Output, all deterministic (no timestamps, no absolute paths, sorted where
order carries no meaning):

    Cargo.toml
    src/main.rs        entry point
    src/routes.rs      the URL tree, in Django's order
    src/handlers.rs    generated Rust handlers (only for views that translate)
    djrs-coverage.json every view: answered in Rust or forwarded, and why
    COVERAGE.md        the same, for people
"""

from __future__ import annotations

import os

from djrs import __version__, ir

from . import entities, handlers, pyregex, settings_rs
from .eligibility import project_blockers, view_blockers
from .rust import crate_name, json_literal, raw_str

HEADER = "// Generated by djrs {version}. Do not edit: run `djrs generate` again instead.\n"


class Report:
    def __init__(self, project, views):
        self.project = project  # list of project-level blockers
        self.views = views  # view id -> {"status", "reasons", ...}

    def counts(self):
        native = sum(1 for v in self.views.values() if v["status"] == "rust")
        return native, len(self.views) - native

    def summary(self):
        native, forwarded = self.counts()
        return "%d views: %d answered in Rust, %d forwarded to Django" % (len(self.views), native, forwarded)


def _write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def _pattern_expr(p, opaque_notes):
    kind = p.get("kind")
    is_endpoint = "true" if p.get("is_endpoint") else "false"
    if kind in ("regex", "route"):
        rust_src, reason = pyregex.translate(p["regex"])
        if rust_src is None:
            opaque_notes.append("%s: %s" % (p["regex"], reason))
            return "Pattern::opaque(%s)" % raw_str("%s (%s)" % (p["regex"], reason))
        if kind == "regex":
            return "Pattern::regex(%s, %s)" % (raw_str(rust_src), is_endpoint)
        convs = ", ".join("(%s, %s)" % (raw_str(k), raw_str(v)) for k, v in sorted(p.get("converters", {}).items()))
        return "Pattern::route(%s, %s, &[%s])" % (raw_str(rust_src), is_endpoint, convs)
    reason = p.get("reason") or "unsupported pattern"
    opaque_notes.append(reason)
    return "Pattern::opaque(%s)" % raw_str(reason)


def _node_expr(node, indent, opaque_notes):
    pad = "    " * indent
    if node["type"] == "endpoint":
        return "%sNode::endpoint(%s, %s, %s)" % (
            pad,
            _pattern_expr(node["pattern"], opaque_notes),
            json_literal(node.get("default_kwargs")),
            raw_str(node["view"]),
        )
    if node["type"] == "resolver":
        children = ",\n".join(_node_expr(c, indent + 1, opaque_notes) for c in node.get("children", []))
        if node.get("error"):
            # The include() failed during extraction: nothing under it can be known.
            return "%sNode::opaque(%s)" % (pad, raw_str("include failed during extraction: " + node["error"]))
        return "%sNode::resolver(\n%s    %s,\n%s    %s,\n%s    vec![\n%s\n%s    ],\n%s)" % (
            pad,
            pad,
            _pattern_expr(node["pattern"], opaque_notes),
            pad,
            json_literal(node.get("default_kwargs")),
            pad,
            children,
            pad,
            pad,
        )
    return "%sNode::opaque(%s)" % (pad, raw_str("unknown urlpatterns entry: %s" % node.get("class")))


def _url_index(tree):
    """view id -> list of the full regex chains that reach it (for the report)."""
    out = {}

    def walk(node, prefix):
        p = node.get("pattern") or {}
        here = prefix + [p.get("route") or p.get("regex") or "?"]
        if node["type"] == "endpoint":
            out.setdefault(node["view"], []).append(" ".join(here[1:]))
        for c in node.get("children", []):
            walk(c, here)

    walk(tree, [])
    return out


def _runtime_dep(runtime, out_dir):
    if runtime and runtime != "git":
        rel = os.path.relpath(os.path.abspath(runtime), os.path.abspath(out_dir)).replace(os.sep, "/")
        return '{ path = "%s" }' % rel
    return '{ git = "https://github.com/amirnouraein/djrs", tag = "v%s" }' % __version__


def generate(data, out_dir, name=None, runtime=None, path_base=None, config=None, config_dir=None):
    """Write the crate into out_dir. `path_base` is the directory the crate will
    finally live in (relative paths are computed from it); defaults to out_dir.
    `config` is the parsed djrs.toml (or None) and `config_dir` its directory."""
    name = crate_name(name or (data["project"].get("settings_module") or "app").split(".")[0] + "-gateway")
    header = HEADER.format(version=__version__)
    final_dir = os.path.abspath(path_base or out_dir)

    # ---- decide every view --------------------------------------------------
    blockers = project_blockers(data)
    settings_src, settings_problems = settings_rs.build(data)
    blockers = blockers + settings_problems
    handlers_body, shim_decls, handled = handlers.build(
        data, config, config_dir or os.getcwd(), os.path.join(final_dir, "src"), blockers
    )
    urls_by_view = _url_index(data["urls"])
    views = {}
    for view_id, view in sorted(data["views"].items()):
        if handled.get(view_id) == []:
            status, reasons = "rust", ["hand-written handler (djrs.toml)"]
        else:
            # Project-wide blockers are reported once, not on every view.
            reasons = handled.get(view_id) or view_blockers(view, data)
            reasons = [r for r in reasons if r not in blockers]
            # Translation arrives in a later milestone; until then every view
            # without a hand-written handler is forwarded, with that reason.
            if not reasons:
                reasons = ["translator: not implemented yet"]
            status = "django"
        views[view_id] = {
            "kind": view.get("kind"),
            "methods": view.get("methods"),
            "urls": urls_by_view.get(view_id, []),
            "status": status,
            "reasons": reasons,
        }
    report = Report(blockers, views)

    # ---- files ---------------------------------------------------------------
    entities_src, model_report = entities.build(data)
    entities_rs = (
        header
        + "\n"
        + "//! One SeaORM entity per concrete model, typed as Django stores it on this database.\n"
        + "#![allow(dead_code)]\n\n"
        + entities_src
    )
    opaque_notes = []
    tree_expr = _node_expr(data["urls"], 2, opaque_notes)
    sem = data.get("url_semantics") or {}
    routes_rs = (
        header
        + "\n"
        + "use djrs_runtime::urls::{Node, Pattern, Semantics, UrlTree};\n\n"
        + "pub fn tree() -> UrlTree {\n"
        + "    UrlTree::new(\n"
        + "        Semantics {\n"
        + "            regex_endpoint_fullmatch_on_dollar: %s,\n" % ("true" if sem.get("regex_endpoint_fullmatch_on_dollar") else "false")
        + "            drop_none_kwargs: %s,\n" % ("true" if sem.get("drop_none_kwargs") else "false")
        + "        },\n"
        + tree_expr
        + ",\n    )\n}\n"
    )
    handlers_rs = header + "\n" + handlers_body
    main_rs = (
        header
        + "\n"
        + "mod entities;\n"
        + "mod handlers;\n"
        + "mod routes;\n"
        + "mod settings;\n\n"
        + ("// Hand-written Rust from djrs.toml [shims].\n" + shim_decls + "\n" if shim_decls else "")
        + "fn main() {\n"
        + "    let app = djrs_runtime::App::new(%s, routes::tree()).settings(&settings::SETTINGS);\n" % raw_str(name)
        + "    djrs_runtime::run(handlers::register(app));\n"
        + "}\n"
    )
    cargo_toml = (
        "# Generated by djrs %s. Do not edit: run `djrs generate` again instead.\n" % __version__
        + "[package]\n"
        + 'name = "%s"\n' % name
        + 'version = "0.1.0"\n'
        + 'edition = "2021"\n'
        + "publish = false\n\n"
        + "[dependencies]\n"
        + "djrs-runtime = %s\n" % _runtime_dep(runtime, path_base or out_dir)
        + 'chrono = { version = "0.4", default-features = false, features = ["clock", "std"] }\n'
        + 'sea-orm = { version = "1.1", default-features = false, features = ["macros", "with-chrono", "with-json", "with-uuid", "with-rust_decimal"] }\n'
        + 'rust_decimal = "1"\n'
        + 'serde_json = { version = "1", features = ["preserve_order"] }\n\n'
        + "[profile.release]\n"
        + "lto = true\n"
        + "codegen-units = 1\n\n"
        + "# Standalone: never part of a surrounding workspace.\n"
        + "[workspace]\n"
    )
    coverage = {
        "djrs": __version__,
        "project_blockers": blockers,
        "opaque_patterns": sorted(set(opaque_notes)),
        "summary": {"views": len(views), "rust": report.counts()[0], "django": report.counts()[1]},
        "views": views,
        "models": model_report,
    }

    _write(os.path.join(out_dir, "Cargo.toml"), cargo_toml)
    _write(os.path.join(out_dir, ".gitignore"), "/target/\n")
    _write(os.path.join(out_dir, "src", "main.rs"), main_rs)
    _write(os.path.join(out_dir, "src", "routes.rs"), routes_rs)
    _write(os.path.join(out_dir, "src", "handlers.rs"), handlers_rs)
    _write(os.path.join(out_dir, "src", "entities.rs"), entities_rs)
    _write(os.path.join(out_dir, "src", "settings.rs"), header + "\n" + settings_src)
    _write(os.path.join(out_dir, "djrs-coverage.json"), ir.dumps(coverage))
    _write(os.path.join(out_dir, "COVERAGE.md"), _coverage_md(coverage))
    return report


def _coverage_md(cov):
    lines = ["# djrs coverage", ""]
    s = cov["summary"]
    lines.append("%d views: %d answered in Rust, %d forwarded to Django." % (s["views"], s["rust"], s["django"]))
    lines.append("")
    if cov["project_blockers"]:
        lines.append("## Blocks every view")
        lines.append("")
        lines.append("Until these are resolved (supported by djrs, or mapped in the project's config), no view is answered in Rust.")
        lines.append("")
        for b in cov["project_blockers"]:
            lines.append("- %s" % b)
        lines.append("")
    by_reason = {}
    for view_id, v in cov["views"].items():
        for r in v["reasons"]:
            by_reason.setdefault(r, []).append(view_id)
    if by_reason:
        lines.append("## Other reasons views are forwarded")
        lines.append("")
        lines.append("| Reason | Views |")
        lines.append("| --- | --- |")
        for reason, ids in sorted(by_reason.items(), key=lambda kv: (-len(kv[1]), kv[0])):
            lines.append("| %s | %d |" % (reason.replace("|", "\\|"), len(ids)))
        lines.append("")
    if cov["opaque_patterns"]:
        lines.append("## URL patterns that can't be matched in Rust")
        lines.append("")
        lines.append("Requests that reach these go to Django.")
        lines.append("")
        for p in cov["opaque_patterns"]:
            lines.append("- `%s`" % p)
        lines.append("")
    partial = {k: v for k, v in sorted(cov.get("models", {}).items()) if not v["complete"]}
    if partial:
        lines.append("## Models Rust can't fully write")
        lines.append("")
        lines.append("| Model | Left out |")
        lines.append("| --- | --- |")
        for label, v in partial.items():
            lines.append("| `%s` | %s |" % (label, "; ".join(v["skipped"]).replace("|", "\\|")))
        lines.append("")
    lines.append("## Views")
    lines.append("")
    lines.append("| View | Kind | Methods | Answered by | Reasons |")
    lines.append("| --- | --- | --- | --- | --- |")
    for view_id, v in cov["views"].items():
        methods = ", ".join(v["methods"]) if v["methods"] else "any"
        lines.append(
            "| `%s` | %s | %s | %s | %s |"
            % (view_id, v["kind"], methods, "Rust" if v["status"] == "rust" else "Django", "; ".join(v["reasons"]).replace("|", "\\|"))
        )
    lines.append("")
    return "\n".join(lines)
